package ai.meshkit.core

/** Mirrors the Swift `MeshKitValidationError` cases used by the trust layer. */
enum class MeshValidationCode {
    INVALID_ENCODING,
    CALLER_IDENTITY_MISMATCH,
    TARGET_IDENTITY_MISMATCH,
    UNSUPPORTED_CAPABILITY,
    TRUSTED_CALLER_MISMATCH,
    CALLER_BUNDLE_CLAIM_MISMATCH,
    OBSERVED_CALLER_REQUIRED,
    OBSERVED_CALLER_MISMATCH,
    OBSERVED_CALLER_SIGNATURE_MISMATCH,
    PAYLOAD_HASH_MISMATCH,
    UNSUPPORTED_PAYLOAD_HASH_ALGORITHM,
    STALE_TIMESTAMP,
    REPLAY_DETECTED,
    SIGNATURE_REQUIRED,
    SIGNATURE_MISMATCH,
    REGISTRY_TRUST_REQUIRED,
    CONSENT_REQUIRED,
    BUDGET_REQUIRED,
    BUDGET_EXCEEDED,
    PRODUCTION_DISABLED,
    INVALID_SECURITY_FIELD,
    RECEIPT_CORRELATION_MISMATCH
}

class MeshValidationException(
    val code: MeshValidationCode,
    message: String
) : Exception(message)
